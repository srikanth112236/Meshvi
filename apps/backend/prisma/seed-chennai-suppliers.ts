async function main() {
  console.log(`Starting seeding of ${suppliers.length} authentic food ingredient suppliers in Chennai...`);

  for (const s of suppliers) {
    // Upsert company
    let company = await prisma.company.findFirst({
      where: { domain: s.company.domain },
    });

    if (!company) {
      company = await prisma.company.create({
        data: {
          ...s.company,
          verificationStatus: 'VERIFIED' as any,
          companyType: 'ENTERPRISE' as any,
        },
      });
      console.log(`Created Company: ${company.name}`);
    } else {
      console.log(`Company exists: ${company.name}`);
    }

    // Upsert Profile
    let profile = await prisma.professionalProfile.findFirst({
      where: { displayName: s.profile.displayName, currentCompanyId: company.id },
    });

    if (!profile) {
      profile = await prisma.professionalProfile.create({
        data: {
          ...s.profile,
          verificationStatus: 'VERIFIED' as any,
          company: { connect: { id: company.id } },
        },
      });
      console.log(`  Created Profile: ${profile.displayName} (${profile.currentTitle})`);

      // Add Expertise
      for (const exp of s.expertise) {
        await prisma.professionalExpertise.create({
          data: {
            professionalProfileId: profile.id,
            term: exp,
            normalizedTerm: exp.toLowerCase(),
          },
        });
      }

      // Add Intent
      await prisma.professionalIntent.create({
        data: {
          professionalProfileId: profile.id,
          intentType: s.intent.intentType,
          description: s.intent.description,
        },
      });
    } else {
      console.log(`  Profile exists: ${profile.displayName}`);
    }
  }

  console.log('Seeding completed successfully!');
  await prisma.$disconnect();
}

main().catch((e) => {
  console.error('Seeding error:', e);
  prisma.$disconnect();
  process.exit(1);
});
